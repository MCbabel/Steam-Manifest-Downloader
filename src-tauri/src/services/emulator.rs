fn render_sections(sections: &[(String, Vec<(String, String)>)]) -> String {
    if sections.is_empty() {
        return String::new();
    }
    let mut out = String::from(INI_HEADER);
    for (i, (name, kvs)) in sections.iter().enumerate() {
        if i > 0 {
            out.push('\n');
        }
        out.push('[');
        out.push_str(name);
        out.push_str("]\n");
        for (k, v) in kvs {
            out.push_str(k);
            out.push('=');
            out.push_str(v);
            out.push('\n');
        }
    }
    out
}

