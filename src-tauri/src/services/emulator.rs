pub async fn fetch_release_info(client: &Client, app_data_dir: &Path) -> Result<ReleaseInfo, String> {
    let resp = client
        .get(RELEASES_API)
        .header("User-Agent", USER_AGENT)
        .header("Accept", "application/vnd.github+json")
        .timeout(Duration::from_secs(30))
        .send()
        .await
        .map_err(|e| format!("GitHub fetch failed: {}", e))?;

    if !resp.status().is_success() {
        return Err(format!("GitHub returned HTTP {}", resp.status()));
    }

    let body: serde_json::Value = resp
        .json()
        .await
        .map_err(|e| format!("GitHub JSON parse failed: {}", e))?;

    let tag = body
        .get("tag_name")
        .and_then(|v| v.as_str())
        .ok_or("Missing tag_name in release info")?
        .to_string();
    let published_at = body
        .get("published_at")
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .to_string();

    let assets = body
        .get("assets")
        .and_then(|v| v.as_array())
        .ok_or("Missing assets array")?;

    let pick = |name: &str| -> Result<(String, u64), String> {
        let a = assets
            .iter()
            .find(|a| a.get("name").and_then(|v| v.as_str()) == Some(name))
            .ok_or_else(|| format!("Asset {} not present in release", name))?;
        let url = a
            .get("browser_download_url")
            .and_then(|v| v.as_str())
            .ok_or("Asset has no browser_download_url")?
            .to_string();
        let size = a.get("size").and_then(|v| v.as_u64()).unwrap_or(0);
        Ok((url, size))
    };

    let (windows_url, windows_size) = pick(Platform::Windows.asset_name())?;
    let (linux_url, linux_size) = pick(Platform::Linux.asset_name())?;

    let root = cache_root(app_data_dir).join(&tag);
    let windows_cached = root.join(Platform::Windows.cache_subdir()).join(".extracted").exists();
    let linux_cached = root.join(Platform::Linux.cache_subdir()).join(".extracted").exists();

    Ok(ReleaseInfo {
        tag,
        published_at,
        windows_url,
        windows_size,
        linux_url,
        linux_size,
        windows_cached,
        linux_cached,
        cache_root: root.to_string_lossy().to_string(),
    })
}

pub async fn ensure_cached(
    client: &Client,
    info: &ReleaseInfo,
    platform: Platform,
) -> Result<PathBuf, String> {
    let platform_dir = PathBuf::from(&info.cache_root).join(platform.cache_subdir());
    let extracted_marker = platform_dir.join(".extracted");
    if extracted_marker.exists() {
        return Ok(platform_dir);
    }

    fs::create_dir_all(&platform_dir).map_err(|e| format!("create cache dir: {}", e))?;
    let asset_name = platform.asset_name();
    let asset_url = match platform {
        Platform::Windows => &info.windows_url,
        Platform::Linux => &info.linux_url,
    };
    let archive_path = platform_dir.join(asset_name);

    if !archive_path.exists() {
        let mut resp = client
            .get(asset_url)
            .header("User-Agent", USER_AGENT)
            .timeout(Duration::from_secs(600))
            .send()
            .await
            .map_err(|e| format!("download failed: {}", e))?;
        if !resp.status().is_success() {
            return Err(format!("download returned HTTP {}", resp.status()));
        }
        let tmp_path = platform_dir.join(format!("{}.part", asset_name));
        {
            let mut file =
                BufWriter::new(File::create(&tmp_path).map_err(|e| format!("create archive: {}", e))?);
            while let Some(chunk) = resp.chunk().await.map_err(|e| format!("chunk: {}", e))? {
                file.write_all(&chunk).map_err(|e| format!("write archive: {}", e))?;
            }
            file.flush().map_err(|e| format!("flush archive: {}", e))?;
        }
        fs::rename(&tmp_path, &archive_path).map_err(|e| format!("finalize archive: {}", e))?;
    }

    if let Err(e) = extract_archive(&archive_path, &platform_dir, platform) {
        if e.starts_with("AV_BLOCKED") {
            let _ = fs::remove_file(&archive_path);
        }
        return Err(e);
    }
    fs::write(&extracted_marker, info.tag.as_bytes())
        .map_err(|e| format!("write extracted marker: {}", e))?;

    Ok(platform_dir)
}

fn extract_archive(archive: &Path, dst: &Path, platform: Platform) -> Result<(), String> {
    match platform {
        Platform::Linux => extract_tar_bz2(archive, dst),
        Platform::Windows => extract_7z(archive, dst),
    }
}

fn extract_tar_bz2(archive: &Path, dst: &Path) -> Result<(), String> {
    let file = File::open(archive).map_err(|e| format!("open archive: {}", e))?;
    let mut decoder = BzDecoder::new(BufReader::new(file));
    let mut tmp = Vec::with_capacity(64 * 1024 * 1024);
    decoder
        .read_to_end(&mut tmp)
        .map_err(|e| format!("bzip2 decompress: {}", e))?;
    let mut tar = Archive::new(io::Cursor::new(tmp));
    tar.unpack(dst).map_err(|e| format!("tar unpack: {}", e))?;
    Ok(())
}

fn extract_7z(archive: &Path, dst: &Path) -> Result<(), String> {
    sevenz_rust::decompress_file(archive, dst).map_err(|e| {
        let msg = e.to_string();
        if is_antivirus_block(&msg) {
            format!("AV_BLOCKED: {}", msg)
        } else {
            format!("7z decompress: {}", msg)
        }
    })
}

fn is_antivirus_block(msg: &str) -> bool {
    let lower = msg.to_lowercase();
    msg.contains("code: 225")
        || lower.contains("virus")
        || lower.contains("unerwünschte software")
        || lower.contains("unwanted software")
}

fn release_root(platform_cache: &Path) -> PathBuf {
    platform_cache.join("release")
}

fn arch_dirs(x64: bool) -> &'static [&'static str] {
    if x64 {
        &["x64"]
    } else {
        &["x86", "x32"]
    }
}

pub fn dll_source(
    platform_cache: &Path,
    variant: Variant,
    x64: bool,
    platform: Platform,
) -> Result<PathBuf, String> {
    let root = release_root(platform_cache).join(variant.folder());
    let filename = platform.emu_filename(x64);
    let mut tried = Vec::new();
    for dir in arch_dirs(x64) {
        let p = root.join(dir).join(filename);
        if p.exists() {
            return Ok(p);
        }
        tried.push(p.display().to_string());
    }
    Err(format!("emulator binary not found, tried: {}", tried.join(", ")))
}

pub fn scan_game_dir(game_dir: &Path) -> Vec<ScannedFile> {
    let mut out = Vec::new();
    if !game_dir.exists() {
        return out;
    }
    for entry in WalkDir::new(game_dir).follow_links(false).into_iter().flatten() {
        if !entry.file_type().is_file() {
            continue;
        }
        let name = entry.file_name().to_string_lossy().to_ascii_lowercase();
        let (platform, arch) = if name == "steam_api64.dll" {
            (Platform::Windows, "x64")
        } else if name == "steam_api.dll" {
            (Platform::Windows, "x32")
        } else if name == "libsteam_api.so" {
            (Platform::Linux, detect_so_arch(entry.path()))
        } else {
            continue;
        };
        let is_patched = backup_path_for(entry.path()).exists();
        out.push(ScannedFile {
            path: entry.path().to_string_lossy().to_string(),
            platform,
            arch: arch.to_string(),
            is_patched,
        });
    }
    out
}

fn detect_so_arch(path: &Path) -> &'static str {
    let Ok(mut file) = File::open(path) else {
        return "x64";
    };
    let mut header = [0u8; 5];
    if file.read_exact(&mut header).is_err() {
        return "x64";
    }
    if &header[..4] != b"\x7fELF" {
        return "x64";
    }
    match header[4] {
        1 => "x32",
        2 => "x64",
        _ => "x64",
    }
}

